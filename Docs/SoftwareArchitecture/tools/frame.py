"""Page frame in the Philosophy notes style (dark-noir-docs, multi-page site):
crumbs, English h1, Vietnamese summary, an Updated fact, then a dl.kv block with
Thuộc / Trang con / Liên quan, the body, the pager. Titles and links come from sections.py."""
import json, os
import sections as S

OUT = os.environ.get("SITE_OUT", os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SITE_TITLE = S.SITE


def rel(from_path, to_path):
    """Relative link from one page to another (both are paths from the site root)."""
    depth = from_path.count("/")
    return "../" * depth + to_path


def a(from_path, to_path):
    target = to_path.split("#")[0]
    return '<a href="' + rel(from_path, to_path) + '">' + S.PAGES[target][0] + '</a>'


def kv_block(path):
    rows = []
    parent = S.parent_of(path)
    if parent:
        rows.append(("Thuộc", a(path, parent)))
    kids = S.children_of(path)
    if kids:
        rows.append(("Trang con", " · ".join(a(path, k) for k in kids)))
    related = S.RELATED.get(path)
    if related:
        rows.append(("Liên quan", " · ".join(a(path, r) for r in related)))
    if not rows:
        return ""
    return '<dl class="kv">\n' + "\n".join(f"  <dt>{k}</dt><dd>{v}</dd>" for k, v in rows) + "\n</dl>\n"


def crumbs(path):
    if path == "index.html":
        return SITE_TITLE
    parts = ['<a href="' + rel(path, "index.html") + '">' + SITE_TITLE + '</a>']
    parent = S.parent_of(path)
    if parent and parent != "index.html":
        parts.append('<a href="' + rel(path, parent) + '">' + S.PAGES[parent][0] + '</a>')
    return '<span class="sep">/</span>'.join(parts)


def write(path, title=None, body="", tags=None, section=None, lang="vi", facts=None, **_):
    """title / tags / section are accepted for old call sites but come from sections.py."""
    title_en, summary = S.PAGES[path]
    root = "../" * path.count("/")
    fact_html = "".join(f'<span class="fact"><b>{k}</b> {v}</span>' for k, v in (facts or []))
    fact_html += f'<span class="fact"><b>Updated</b> {S.UPDATED}</span>'
    page_title = SITE_TITLE if path == "index.html" else title_en + " · " + SITE_TITLE
    html = f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{page_title}</title>
<link rel="stylesheet" href="{root}assets/noir.css">
<link rel="stylesheet" href="{root}assets/site.css">
<link rel="stylesheet" href="{root}assets/arch.css">
</head>
<body data-root="{root}" data-page="{path}">
<header class="top">
  <div class="top-inner">
    <div class="crumbs">{crumbs(path)}</div>
    <h1>{title_en}</h1>
    <p class="summary">{summary}</p>
    <div class="facts">
      {fact_html}
    </div>
  </div>
</header>

<div class="layout">
<aside class="side"></aside>
<main>

{kv_block(path)}{body.strip()}

<nav class="pager" aria-label="Pages"></nav>
<footer>{title_en}</footer>
</main>
</div>
<script src="{root}assets/site.js"></script>
<script src="{root}assets/noir.js"></script>
<script src="{root}assets/diagram-view.js"></script>
</body>
</html>
"""
    full = os.path.join(OUT, path.replace("/", os.sep))
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)


def write_site_js():
    def node(p, children=None):
        n = {"t": S.PAGES[p][0], "h": p}
        if children:
            n["c"] = children
        return n
    tree = [node("index.html", [node(hub, [node(c) for c in kids]) for hub, kids in S.TREE])]
    js = ("// Site map for noir.js: page titles and paths relative to the site root.\n"
          "// Generated by tools/build.py from tools/sections.py; edit there, not here.\n"
          "window.SITE = " + json.dumps({"title": "Contents", "pages": tree}, ensure_ascii=False, indent=1) + ";\n")
    with open(os.path.join(OUT, "assets", "site.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(js)


def section_index(section_hub, intro, tags=None):
    """A branch hub: intro, then one row per page with its Vietnamese summary."""
    kids = S.children_of(section_hub)
    rows = "\n".join(
        f'<tr><td class="nowrap"><a href="{k.split("/")[-1]}"><strong>{S.PAGES[k][0]}</strong></a></td><td>{S.PAGES[k][1]}</td></tr>'
        for k in kids)
    body = (f'<h2 id="tong-quan">Tổng quan</h2>\n{intro}\n<div class="table-wrap"><table>\n'
            f'<thead><tr><th>Trang</th><th>Nội dung</th></tr></thead>\n<tbody>\n{rows}\n</tbody>\n</table></div>')
    write(section_hub, body=body, facts=[("Trang", len(kids))])
